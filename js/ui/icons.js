/**
 * Marcação SVG completa de um ícone, ou null se o nome não existir.
 * @param {string} name
 * @param {string} [extraClass] classes a preservar do placeholder
 * @returns {string | null}
 */
function iconMarkup(name, extraClass = "") {
  const inner = ICON_PATHS[name];
  if (inner == null) return null;
  const className = `${extraClass} lucide lucide-${name}`.trim();
  return `<svg ${SVG_ATTRS} class="${className}" aria-hidden="true">${inner}</svg>`;
}

/**
 * Substitui os placeholders `[data-lucide]` dentro de `root` por SVGs inline,
 * preservando as classes do placeholder. Idempotente: placeholders já trocados
 * deixam de existir e são ignorados em chamadas seguintes.
 * @param {ParentNode} [root]
 */
export function refreshIcons(root = document) {
  const placeholders = root.querySelectorAll?.("[data-lucide]");
  if (!placeholders) return;
  placeholders.forEach((element) => {
    const name = element.getAttribute("data-lucide") ?? "";
    const markup = iconMarkup(name, element.getAttribute("class") ?? "");
    if (!markup) return;
    const template = document.createElement("template");
    template.innerHTML = markup;
    const svg = template.content.firstElementChild;
    if (svg) element.replaceWith(svg);
  });
}

/** @returns {string[]} nomes de ícones disponíveis. */
export function availableIcons() {
  return Object.keys(ICON_PATHS);
}
